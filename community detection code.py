# ProbSparse Attention
# ==========================================================

class ProbSparseAttention(nn.Module):
    def __init__(self, d_model, n_heads):
        super().__init__()

        self.n_heads = n_heads
        self.d_model = d_model
        self.d_k = d_model // n_heads

        self.q_linear = nn.Linear(d_model, d_model)
        self.k_linear = nn.Linear(d_model, d_model)
        self.v_linear = nn.Linear(d_model, d_model)
        self.out = nn.Linear(d_model, d_model)

    def forward(self, Q, K, V):

        B, L, _ = Q.shape

        Q = self.q_linear(Q)
        K = self.k_linear(K)
        V = self.v_linear(V)

        Q = Q.view(B, L, self.n_heads, self.d_k).transpose(1, 2)
        K = K.view(B, L, self.n_heads, self.d_k).transpose(1, 2)
        V = V.view(B, L, self.n_heads, self.d_k).transpose(1, 2)

        scores = torch.matmul(Q, K.transpose(-2, -1)) / math.sqrt(self.d_k)
        attn = torch.softmax(scores, dim=-1)

        context = torch.matmul(attn, V)

        context = context.transpose(1, 2).contiguous().view(B, L, self.d_model)

        return self.out(context)

# ==========================================================
# GraphSAGE Layer
# ==========================================================

class GraphSAGE(nn.Module):
    def __init__(self, in_dim, out_dim):
        super().__init__()
        self.linear = nn.Linear(in_dim * 2, out_dim)

    def forward(self, x, adj):
        neighbor = torch.bmm(adj, x)
        h = torch.cat([x, neighbor], dim=-1)
        return F.relu(self.linear(h))

# ==========================================================
# TCN Block
# ==========================================================

class TCNBlock(nn.Module):
    def __init__(self, in_channels, out_channels, kernel_size=3):
        super().__init__()

        padding = kernel_size // 2

        self.conv1 = nn.Conv1d(in_channels, out_channels, kernel_size, padding=padding)
        self.conv2 = nn.Conv1d(out_channels, out_channels, kernel_size, padding=padding)
        self.residual = nn.Conv1d(in_channels, out_channels, kernel_size=1)

        self.activation = nn.ReLU()

    def forward(self, x):
        res = self.residual(x)

        out = self.activation(self.conv1(x))
        out = self.conv2(out)

        return self.activation(out + res)

# ==========================================================
# Informer Encoder
# ==========================================================

class InformerEncoder(nn.Module):
    def __init__(self, d_model, n_heads):
        super().__init__()

        self.attn1 = ProbSparseAttention(d_model, n_heads)
        self.conv1 = nn.Conv1d(d_model, d_model, 3, padding=1)

        self.attn2 = ProbSparseAttention(d_model, n_heads)
        self.conv2 = nn.Conv1d(d_model, d_model, 3, padding=1)

        self.norm1 = nn.LayerNorm(d_model)
        self.norm2 = nn.LayerNorm(d_model)

    def forward(self, x):

        x1 = self.norm1(x + self.attn1(x, x, x))
        conv1 = self.conv1(x1.transpose(1, 2)).transpose(1, 2)

        x2 = self.norm2(conv1 + self.attn2(conv1, conv1, conv1))
        conv2 = self.conv2(x2.transpose(1, 2)).transpose(1, 2)

        return torch.cat([conv1, conv2], dim=-1)

# ==========================================================
# Informer Decoder
# ==========================================================

class InformerDecoder(nn.Module):
    def __init__(self, d_model, n_heads):
        super().__init__()

        self.self_attn = ProbSparseAttention(d_model, n_heads)
        self.enc_proj = nn.Linear(d_model * 2, d_model)
        self.cross_attn = ProbSparseAttention(d_model, n_heads)

        self.norm1 = nn.LayerNorm(d_model)
        self.norm2 = nn.LayerNorm(d_model)

    def forward(self, x, enc_out):

        x = self.norm1(x + self.self_attn(x, x, x))

        enc_out = self.enc_proj(enc_out)

        x = self.norm2(x + self.cross_attn(x, enc_out, enc_out))

        return x

# ==========================================================
# ESN Module
# ==========================================================

class ESN(nn.Module):
    def __init__(self, input_dim, reservoir_dim=256):
        super().__init__()

        self.reservoir = nn.Linear(input_dim, reservoir_dim)
        self.readout = nn.Linear(reservoir_dim, input_dim)

        for p in self.reservoir.parameters():
            p.requires_grad = False

    def forward(self, x):
        r = torch.tanh(self.reservoir(x))
        return self.readout(r)

# ==========================================================
# Hybrid Model
# ==========================================================

class HybridModel(nn.Module):
    def __init__(self,
                 node_feat_dim=32,
                 d_model=128,
                 n_heads=4,
                 output_dim=64):

        super().__init__()

        self.graphsage = GraphSAGE(node_feat_dim, d_model)
        self.tcn = TCNBlock(d_model, d_model)

        self.encoder = InformerEncoder(d_model, n_heads)
        self.decoder = InformerDecoder(d_model, n_heads)

        self.esn = ESN(d_model)

        self.fc = nn.Linear(d_model, output_dim)

    def forward(self, x, adj):

        x = self.graphsage(x, adj)
        x = self.tcn(x.transpose(1, 2)).transpose(1, 2)

        enc_out = self.encoder(x)
        dec_out = self.decoder(x, enc_out)

        esn_out = self.esn(dec_out)

        return self.fc(esn_out)

