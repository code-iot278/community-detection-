# ==========================================================
# 4️⃣ GCN Layer
# ==========================================================

class GCNLayer(nn.Module):
    def __init__(self, in_dim, out_dim):
        super().__init__()
        self.linear = nn.Linear(in_dim, out_dim)

    def forward(self, A, X):
        I = torch.eye(A.size(0)).to(device)
        A_hat = A + I
        D_inv_sqrt = torch.diag(torch.pow(A_hat.sum(1), -0.5))
        A_norm = D_inv_sqrt @ A_hat @ D_inv_sqrt
        return torch.relu(self.linear(A_norm @ X))

# ==========================================================
# 5️⃣ GCN-LSTM Model (FIXED DIMENSIONS)
# ==========================================================

class GCN_LSTM(nn.Module):
    def __init__(self, num_nodes, gcn_dim=64, lstm_dim=64):
        super().__init__()

        # Initial projection
        self.input_proj = nn.Linear(num_nodes, gcn_dim)

        # GCN keeps constant dimension
        self.gcn = GCNLayer(gcn_dim, gcn_dim)

        self.lstm = nn.LSTM(gcn_dim, lstm_dim, batch_first=True)

    def forward(self, snapshots):

        # Initial node identity features
        X = torch.eye(num_nodes).to(device)

        # Project once
        X = torch.relu(self.input_proj(X))

        gcn_outputs = []

        for t in range(T):
            A = snapshots[t]
            X = self.gcn(A, X)
            gcn_outputs.append(X)

        gcn_outputs = torch.stack(gcn_outputs, dim=1)  # (N, T, gcn_dim)

        lstm_out, _ = self.lstm(gcn_outputs)

        return lstm_out[:, -1, :]  # final embeddings


