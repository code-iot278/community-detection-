class DeepWalk:
    def __init__(self, walk_length=10, num_walks=80, embed_dim=64, window_size=5):
        self.walk_length = walk_length
        self.num_walks = num_walks
        self.embed_dim = embed_dim
        self.window_size = window_size

    def generate_walks(self, G):
        walks = []
        nodes = list(G.nodes())

        for _ in range(self.num_walks):
            random.shuffle(nodes)
            for node in nodes:
                walk = [str(node)]
                current = node

                for _ in range(self.walk_length - 1):
                    neighbors = list(G.neighbors(current))
                    if len(neighbors) == 0:
                        break
                    current = random.choice(neighbors)
                    walk.append(str(current))

                walks.append(walk)

        return walks

    def fit(self, G):

        walks = self.generate_walks(G)

        model = Word2Vec(
            sentences=walks,
            vector_size=self.embed_dim,
            window=self.window_size,
            min_count=0,
            sg=1,
            workers=4,
            epochs=5
        )

        embeddings = np.zeros((num_nodes, self.embed_dim))

        # Only assign embeddings to nodes that exist in graph
        for node in G.nodes():
            embeddings[node] = model.wv[str(node)]

        return embeddings

